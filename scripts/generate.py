"""Regenerates the client in src/ from the API description listed in apis.yaml.

    uv run python scripts/generate.py           # from the committed spec in specs/
    uv run python scripts/generate.py --fetch   # download the latest spec first

Never edit generated code by hand: change apis.yaml, the auth class in
src/stripe_apiroute/auth.py, scripts/stripe_names.py, or apiroute itself, then regenerate.
The Build workflow runs this with --fetch every week and commits whatever changes.

Before generating, it writes from the spec the operation-name map (specs/stripe.names.json,
from x-stripeOperations) and src/stripe_apiroute/spec_info.py: the API version the spec, and
so the typed models, describe, and the operations served from another host (file uploads
go to files.stripe.com). Both follow every spec update.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

import httpx
import stripe_names
import yaml

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Generated by scripts/generate.py from apis.yaml. Do not edit: regenerate instead."


def main() -> int:
    arguments = _parser().parse_args()
    config = yaml.safe_load((ROOT / "apis.yaml").read_text())
    apis = [api for api in config["apis"] if not arguments.only or api["name"] in arguments.only]
    if arguments.only and len(apis) != len(arguments.only):
        print(f"unknown API name in {arguments.only}", file=sys.stderr)
        return 1
    package_dir = ROOT / "src" / config["package"]
    for api in apis:
        spec = ROOT / "specs" / f"{api['name']}.json"
        if arguments.fetch:
            _fetch(api, spec)
        if api.get("operation_names"):
            stripe_names.write(spec, ROOT / api["operation_names"])
        _write_spec_info(spec, package_dir)
        _generate(api, spec, package_dir)
    _write_readme_table(config)
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--fetch", action="store_true", help="download the latest spec first")
    parser.add_argument("--only", nargs="+", metavar="NAME", help="only these APIs (by name)")
    return parser


def _fetch(api: dict, spec: Path) -> None:
    """Saves the spec as published. JSON is re-indented so that a reformatted upload doesn't
    show up as a change; key order is kept, since the generator follows it."""
    response = httpx.get(api["spec"], follow_redirects=True, timeout=120)
    response.raise_for_status()
    document = response.json()  # an HTML error page would fail here, not later
    if "openapi" not in document:
        raise ValueError(f"{api['name']}: {api['spec']} isn't an OpenAPI document")
    spec.parent.mkdir(exist_ok=True)
    spec.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n")
    print(f"fetched {api['name']}")


def _write_spec_info(spec: Path, package_dir: Path) -> None:
    """What StripeAuth reads from the spec: the API version, sent as Stripe-Version so that
    responses have the shape the generated models expect, and each operation's own server."""
    document = json.loads(spec.read_text())
    servers = {
        operation["operationId"]: operation["servers"][0]["url"].rstrip("/")
        for item in document["paths"].values()
        for operation in item.values()
        if isinstance(operation, dict) and operation.get("servers")
    }
    entries = [
        f"    {json.dumps(name)}: {json.dumps(url)},\n" for name, url in sorted(servers.items())
    ]
    (package_dir / "spec_info.py").write_text(
        f"{MARKER}\n"
        '"""What the client takes from Stripe\'s spec."""\n\n'
        "# The Stripe API version the spec, and so the typed models, describe\n"
        f"STRIPE_VERSION = {json.dumps(document['info']['version'])}\n\n"
        "# Operations served from a host of their own (file uploads, PDFs), by operation ID\n"
        "OPERATION_SERVERS = {\n" + "".join(entries) + "}\n"
    )


def _generate(api: dict, spec: Path, package_dir: Path) -> None:
    out = package_dir.joinpath(*api["module"].split("."))
    command = [
        "apiroute",
        "generate",
        "openapi",
        str(spec),
        "-o",
        str(out),
        "--client-name",
        api["client"],
    ]
    if api.get("models", True):
        command.append("--models")
    if api.get("base_class"):
        command += ["--base-class", api["base_class"]]
    if api.get("nullable_fields"):
        command.append("--nullable-fields")
    if api.get("operation_names"):
        command += ["--operation-names", str(ROOT / api["operation_names"])]
    subprocess.run(command, check=True)


def _write_readme_table(config: dict) -> None:
    """The README's table of APIs, between its apis:start and apis:end markers."""
    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = "<!-- apis:start -->", "<!-- apis:end -->"
    if start not in text or end not in text:
        return
    rows = ["| API | Import | Docs |", "| --- | --- | --- |"]
    for api in config["apis"]:
        module = f"{config['package']}.{api['module']}"
        rows.append(
            f"| {api['title']} | `from {module} import {api['client']}` | [docs]({api['docs']}) |"
        )
    table = "\n".join(rows)
    before, rest = text.split(start, 1)
    after = rest.split(end, 1)[1]
    readme.write_text(f"{before}{start}\n{table}\n{end}{after}")


if __name__ == "__main__":
    sys.exit(main())
